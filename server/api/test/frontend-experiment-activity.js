'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const html=fs.readFileSync(path.resolve(__dirname,'../../../index.html'),'utf8');
const start=html.indexOf('/* ---------- experiment activity ---------- */');
const end=html.indexOf('function mount(i)',start);
assert(start>=0&&end>start,'App必须建立独立的当前实验活动通知');
const messages=[],listeners={},frames=[0,1,2].map(i=>({src:'https://html.xingnian.net.cn/physics-middle/'+i+'.html',contentWindow:{postMessage(data,origin){messages.push({i,data,origin});}}}));
const document={hidden:false,addEventListener(name,fn){listeners[name]=fn;}};
const window={location:{href:'https://lab.xingnian.net.cn/'},addEventListener(name,fn){listeners[name]=fn;}};
const context=vm.createContext({document,window,URL,console,pages:frames.map(f=>({querySelector:()=>f})),cur:1});
vm.runInContext(html.slice(start,end),context);
vm.runInContext('syncExperimentActivity()',context);
assert.deepStrictEqual(messages.map(x=>[x.i,x.data.active]),[[0,false],[1,true],[2,false]]);
assert(messages.every(x=>x.origin==='https://html.xingnian.net.cn'));
assert(messages.every(x=>x.data.channel==='xingnian-experiment-activity'&&Number.isSafeInteger(x.data.sequence)));
assert(messages.every((x,i)=>i===0||x.data.sequence>messages[i-1].data.sequence));
messages.length=0;document.hidden=true;listeners.visibilitychange();assert(messages.every(x=>x.data.active===false),'切后台应停用所有已挂载实验');
document.hidden=false;messages.length=0;listeners.pageshow();assert.strictEqual(messages.find(x=>x.i===1).data.active,true);
messages.length=0;listeners.pagehide();assert(messages.every(x=>x.data.active===false),'离开App应通知所有现存iframe');
assert.match(html,/notifyExperimentActivity\(f,\s*i===cur/,'新加载iframe按实际当前实验通知');
assert.match(html,/notifyExperimentActivity\(f,\s*false\);\s*f\.remove\(/,'卸载前先发停用');
assert.match(html,/function render\(\)[\s\S]*syncExperimentActivity\(/,'切换后同步当前活动页');
console.log('✓ 当前iframe、后台/恢复、离开和卸载的独立活动通知通过');
